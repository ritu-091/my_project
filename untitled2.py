def processData():

    # ==========================================
    # 1. Load dataset
    # ==========================================
    data = pd.read_csv('/content/Train_Test_Network.csv')


    # ==========================================
    # 2. Select the 6 classes we need
    # ==========================================
    selected_classes = [
        'normal',
        'scanning',
        'dos',
        'ddos',
        'ransomware',
        'backdoor'
    ]

    data = data[data['type'].isin(selected_classes)].copy()


    # ==========================================
    # 3. Select our 10 network features
    # ==========================================
    features = [
        'duration',
        'src_port',
        'dst_port',
        'proto',
        'src_bytes',
        'dst_bytes',
        'src_pkts',
        'dst_pkts',
        'src_ip_bytes',
        'dst_ip_bytes'
    ]

    data = data[features + ['type']]


    # ==========================================
    # 4. Convert protocol to numbers
    # ==========================================
    protocol_map = {
        'tcp': 1,
        'udp': 2,
        'icmp': 3
    }

    data['proto'] = data['proto'].map(protocol_map)


    # ==========================================
    # 5. Convert attack classes to numbers
    # ==========================================
    type_map = {
        'normal': 0,
        'scanning': 1,
        'dos': 2,
        'ddos': 3,
        'ransomware': 4,
        'backdoor': 5
    }

    data['type'] = data['type'].map(type_map)


    # ==========================================
    # 6. Remove extreme duration values
    # ==========================================
    data.drop(
        data[data['duration'] > 12000].index,
        inplace=True
    )


    # ==========================================
    # 7. Log transformation
    # ==========================================
    log_features = [
        'duration',
        'src_bytes',
        'dst_bytes',
        'src_pkts',
        'dst_pkts',
        'src_ip_bytes',
        'dst_ip_bytes'
    ]

    for column in log_features:
        data[column] = np.log1p(data[column])


    # ==========================================
    # 8. Remove missing values
    # ==========================================
    data.dropna(inplace=True)


    # ==========================================
    # 9. Create target tensor
    # ==========================================
    target_tensor = torch.tensor(
        data['type'].values,
        dtype=torch.long
    )


    # ==========================================
    # 10. Remove target column
    # ==========================================
    data.drop('type', axis=1, inplace=True)


    # ==========================================
    # 11. Create input tensor
    # ==========================================
    train_tensor = torch.tensor(
        data.values,
        dtype=torch.float32
    )


    # ==========================================
    # 12. Return input and target
    # ==========================================
    return train_tensor, target_tensor

